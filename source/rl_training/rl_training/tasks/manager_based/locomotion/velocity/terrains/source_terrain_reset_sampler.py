"""Deterministic reset-level sampling for the Lite3 Source Terrain columns.

The geometry generator assigns one terrain type to each generated column. This
module schedules those existing columns across episode resets; it does not
generate or mutate terrain geometry. Runtime assignment is deliberately
limited to one environment because multiple robots cannot safely share one
terrain origin.
"""

from __future__ import annotations

import math
import numbers
import random
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any


def terrain_column_subterrain_indices(
    proportions: Mapping[str, float], num_cols: int
) -> tuple[int, ...]:
    """Reproduce Isaac Lab's cumulative proportion-to-column assignment.

    The returned values index ``proportions`` in insertion order, matching
    ``TerrainGenerator._generate_curriculum_terrains``. Isaac Lab adds 0.001
    to each normalized column coordinate before comparing it to the
    cumulative weights; that detail is retained here so the reset scheduler
    targets the columns actually generated by the terrain importer.
    """

    if isinstance(num_cols, bool) or not isinstance(num_cols, int) or num_cols < 1:
        raise ValueError("num_cols must be a positive integer")
    if not isinstance(proportions, Mapping) or not proportions:
        raise ValueError("proportions must be a non-empty ordered mapping")

    names = tuple(proportions)
    weights: list[float] = []
    for name in names:
        value = proportions[name]
        if isinstance(value, bool) or not isinstance(value, numbers.Real):
            raise ValueError(
                f"terrain proportion for {name!r} must be a finite positive number"
            )
        weight = float(value)
        if not math.isfinite(weight) or weight <= 0.0:
            raise ValueError(
                f"terrain proportion for {name!r} must be a finite positive number"
            )
        weights.append(weight)

    total = sum(weights)
    if not math.isfinite(total) or total <= 0.0:
        raise ValueError("terrain proportions must have a finite positive total")

    cumulative: list[float] = []
    running_total = 0.0
    for weight in weights:
        running_total += weight / total
        cumulative.append(running_total)

    assigned: list[int] = []
    for column in range(num_cols):
        coordinate = column / num_cols + 0.001
        selected = next(
            (
                index
                for index, boundary in enumerate(cumulative)
                if coordinate < boundary
            ),
            None,
        )
        if selected is None:
            raise ValueError(
                "terrain proportions do not cover every generated column under Isaac Lab's assignment rule"
            )
        assigned.append(selected)
    if set(assigned) != set(range(len(names))):
        raise ValueError(
            "every configured sub-terrain must occupy at least one generated column"
        )
    return tuple(assigned)


def _validate_seed(seed: int) -> int:
    if isinstance(seed, bool) or not isinstance(seed, int) or seed < 0:
        raise ValueError("sampler_seed must be an explicit nonnegative integer")
    return seed


@dataclass
class ResetBlockTerrainSampler:
    """Shuffle all terrain columns once per deterministic reset block."""

    num_cols: int
    sampler_seed: int

    def __post_init__(self) -> None:
        if (
            isinstance(self.num_cols, bool)
            or not isinstance(self.num_cols, int)
            or self.num_cols < 1
        ):
            raise ValueError("num_cols must be a positive integer")
        self.sampler_seed = _validate_seed(self.sampler_seed)
        self._rng = random.Random(self.sampler_seed)
        self._order: tuple[int, ...] = ()
        self._cursor = self.num_cols

    def next_column(self) -> int:
        """Return the next column, beginning a fresh permutation per block."""

        if self._cursor >= self.num_cols:
            order = list(range(self.num_cols))
            self._rng.shuffle(order)
            self._order = tuple(order)
            self._cursor = 0
        selected = self._order[self._cursor]
        self._cursor += 1
        return selected

    def take(self, count: int) -> tuple[int, ...]:
        """Return ``count`` scheduled columns, including across block edges."""

        if isinstance(count, bool) or not isinstance(count, int) or count < 0:
            raise ValueError("count must be a nonnegative integer")
        return tuple(self.next_column() for _ in range(count))


def _reset_indices(env_ids: Any, num_envs: int) -> tuple[int, ...]:
    if isinstance(env_ids, slice):
        return tuple(range(num_envs)[env_ids])
    if hasattr(env_ids, "reshape") and hasattr(env_ids, "tolist"):
        env_ids = env_ids.reshape(-1).tolist()
    elif hasattr(env_ids, "tolist"):
        env_ids = env_ids.tolist()
    if isinstance(env_ids, numbers.Integral) and not isinstance(env_ids, bool):
        return (int(env_ids),)
    if not isinstance(env_ids, Sequence):
        raise ValueError("env_ids must identify the environment being reset")
    normalized_ids = []
    for env_id in env_ids:
        if isinstance(env_id, bool) or not isinstance(env_id, numbers.Integral):
            raise ValueError("env_ids must contain only integer environment indices")
        normalized_ids.append(int(env_id))
    return tuple(normalized_ids)


def assign_source_terrain_for_reset(
    env: Any, env_ids: Any, sampler_seed: int
) -> int | None:
    """Assign the next balanced terrain column before a single-env reset.

    This function uses only the small public attribute surface shared by
    Isaac Lab environments and terrain importers, which also makes it possible
    to test without starting Isaac Sim.
    """

    num_envs = getattr(env, "num_envs", None)
    if (
        isinstance(num_envs, bool)
        or not isinstance(num_envs, numbers.Integral)
        or num_envs != 1
    ):
        raise RuntimeError(
            "reset-level Source Terrain sampling currently supports exactly one environment; "
            "multi-environment origin allocation needs a separate collision-safe design"
        )
    sampler_seed = _validate_seed(sampler_seed)
    reset_ids = _reset_indices(env_ids, num_envs)
    if not reset_ids:
        return None
    if reset_ids != (0,):
        raise RuntimeError(
            "single-environment Source Terrain sampling only accepts reset env_ids=(0,)"
        )

    scene = getattr(env, "scene", None)
    terrain = getattr(scene, "terrain", None)
    terrain_cfg = getattr(terrain, "cfg", None)
    generator_cfg = getattr(terrain_cfg, "terrain_generator", None)
    if terrain is None or terrain_cfg is None or generator_cfg is None:
        raise RuntimeError(
            "reset-level Source Terrain sampling requires a generated terrain importer"
        )
    if getattr(terrain_cfg, "terrain_type", None) != "generator":
        raise RuntimeError(
            "reset-level Source Terrain sampling requires terrain_type='generator'"
        )
    if not getattr(terrain_cfg, "use_terrain_origins", False):
        raise RuntimeError(
            "reset-level Source Terrain sampling requires terrain origins"
        )
    if getattr(generator_cfg, "num_rows", None) != 1:
        raise RuntimeError(
            "reset-level Source Terrain sampling currently requires exactly one terrain row"
        )

    sub_terrains = getattr(generator_cfg, "sub_terrains", None)
    num_cols = getattr(generator_cfg, "num_cols", None)
    try:
        column_subterrain_indices = terrain_column_subterrain_indices(
            {name: cfg.proportion for name, cfg in sub_terrains.items()}, num_cols
        )
    except (AttributeError, TypeError) as error:
        raise RuntimeError(
            "Source Terrain generator proportions are unavailable or invalid"
        ) from error

    terrain_origins = getattr(terrain, "terrain_origins", None)
    env_origins = getattr(terrain, "env_origins", None)
    terrain_types = getattr(terrain, "terrain_types", None)
    terrain_levels = getattr(terrain, "terrain_levels", None)
    if any(
        value is None
        for value in (terrain_origins, env_origins, terrain_types, terrain_levels)
    ):
        raise RuntimeError(
            "Source Terrain importer does not expose initialized terrain origins and indices"
        )
    if tuple(terrain_origins.shape[:2]) != (1, num_cols):
        raise RuntimeError(
            "Source Terrain origin grid does not match the configured one-row column layout"
        )
    if (
        tuple(env_origins.shape) != (1, 3)
        or tuple(terrain_types.shape) != (1,)
        or tuple(terrain_levels.shape) != (1,)
    ):
        raise RuntimeError(
            "Source Terrain importer buffers do not match single-environment sampling"
        )

    signature = (
        num_cols,
        tuple((name, float(cfg.proportion)) for name, cfg in sub_terrains.items()),
        column_subterrain_indices,
    )
    sampler = getattr(env, "_source_terrain_reset_sampler", None)
    if sampler is None:
        sampler = ResetBlockTerrainSampler(num_cols=num_cols, sampler_seed=sampler_seed)
        env._source_terrain_reset_sampler = sampler
        env._source_terrain_reset_sampler_signature = signature
    else:
        if getattr(env, "_source_terrain_reset_sampler_signature", None) != signature:
            raise RuntimeError(
                "Source Terrain layout changed after reset sampling started"
            )
        if sampler.sampler_seed != sampler_seed:
            raise RuntimeError(
                "sampler_seed cannot change while the Source Terrain environment is running"
            )

    selected_column = sampler.next_column()
    terrain.terrain_levels[0] = 0
    terrain.terrain_types[0] = selected_column
    terrain.env_origins[0] = terrain.terrain_origins[0, selected_column]
    return selected_column


__all__ = [
    "ResetBlockTerrainSampler",
    "assign_source_terrain_for_reset",
    "terrain_column_subterrain_indices",
]
