def slide(source, purpose, title, texts, notes, rows=None, chart=None):
    number = len(slides) + 1
    replacements = []
    if source == 1:
        replacements.append({'slot_id':'s01_sh105','text':title})
    else:
        replacements.extend([{'slot_id':f's{source:02d}_sh112','text':title},
                             {'slot_id':f's{source:02d}_sh114','text':str(number)}])
        replacements.extend({'slot_id':f's{source:02d}_sh{k}','text':v} for k,v in texts.items())
    patterns={1:'校门图片与蓝色封面',2:'四阶段流程与三段说明',3:'四阶段流程与四段说明',4:'横向数据图、指标表与三段解读',5:'日期说明、单段视频与结果解读',6:'核心判断与三行对照表'}
    s={'source_slide':source,'purpose':purpose,'layout_rationale':{
        'layout_pattern':patterns[source], 'why_fit':purpose,
        'risk':'保留模板字号与母版；文字容量校验后逐页渲染复核。'},
       'notes':notes,'transition':'none','replacements':replacements}
    if rows:
        table_id='s04_tbl117' if source==4 else 's06_tbl116'
        s['table_edits']=[{'table_id':table_id,'cells':[{'row':i,'col':j,'text':v} for i,row in enumerate(rows) for j,v in enumerate(row)]}]
    if chart: s['chart_edits']=[{'chart_id':'s04_ch116',**chart}]
    slides.append(s)

